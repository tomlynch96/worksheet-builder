-- If worksheets has an updated_at trigger, switch it off for the run so remapped worksheets do not
-- jump to "just edited" and reorder everyone's gallery. (Production currently has no such trigger,
-- so this is a no-op there, but it must not fail when the trigger is absent.)
do $$
begin
  if exists (select 1 from pg_trigger where tgname = 'worksheets_updated_at' and tgrelid = 'public.worksheets'::regclass) then
    alter table public.worksheets disable trigger worksheets_updated_at;
  end if;
end $$;

-- 1. worksheets.spec_point
with changes as (
  select w.id, w.profile_id, w.spec_point as old_value, m.new_ref
  from public.worksheets w
  join public.spec_ref_map m
    on m.qualification_id = w.qualification_id and m.exam_board = w.exam_board
   and m.kind = 'point' and m.old_ref = w.spec_point
  where m.new_ref is not null
), logged as (
  insert into public.spec_ref_migration_log (batch, tbl, row_id, profile_id, col, old_value, new_value)
  select '026_alevel_spec_refs', 'worksheets', id::text, profile_id, 'spec_point', to_jsonb(old_value), to_jsonb(new_ref) from changes
)
update public.worksheets w set spec_point = c.new_ref from changes c where w.id = c.id;

-- 2. the specPoint stored on the header block inside worksheets.blocks
with changes as (
  select w.id, w.profile_id, h.sp as old_value, m.new_ref
  from public.worksheets w
  cross join lateral (
    select b ->> 'specPoint' as sp
    from jsonb_array_elements(w.blocks) b
    where b ->> 'type' = 'header' and b ->> 'specPoint' is not null
    limit 1
  ) h
  join public.spec_ref_map m
    on m.qualification_id = w.qualification_id and m.exam_board = w.exam_board
   and m.kind = 'point' and m.old_ref = h.sp
  where m.new_ref is not null and jsonb_typeof(w.blocks) = 'array'
), logged as (
  insert into public.spec_ref_migration_log (batch, tbl, row_id, profile_id, col, old_value, new_value)
  select '026_alevel_spec_refs', 'worksheets', id::text, profile_id, 'blocks.header.specPoint', to_jsonb(old_value), to_jsonb(new_ref) from changes
)
update public.worksheets w
set blocks = (
  select jsonb_agg(
           case when b ->> 'type' = 'header' and b ->> 'specPoint' = c.old_value
                then jsonb_set(b, '{specPoint}', to_jsonb(c.new_ref))
                else b end
           order by ord)
  from jsonb_array_elements(w.blocks) with ordinality as t(b, ord)
)
from changes c where w.id = c.id;

