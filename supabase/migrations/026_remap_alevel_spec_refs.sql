begin
  if to_regclass('public.diagrams') is not null then
    with changes as (
      select d.id, d.profile_id, d.spec_points as old_value,
             (select array_agg(e order by first_ord)
              from (
                select coalesce(m.new_ref, x.e) as e, min(x.ord) as first_ord
                from unnest(d.spec_points) with ordinality as x(e, ord)
                left join public.spec_ref_map m
                  on m.qualification_id = d.qualification and m.exam_board = d.exam_board
                 and m.kind = 'point' and m.new_ref is not null
                 and m.old_ref = regexp_replace(x.e, '^(AQA|OCR|Edexcel|WJEC)[- ]+((9PH0|7408|H556)[- ]+)?', '', 'i')
                group by 1
              ) z) as new_value
      from public.diagrams d
      where d.qualification = 'alevel-physics'
        and exists (
          select 1 from unnest(d.spec_points) e
          join public.spec_ref_map m
            on m.qualification_id = d.qualification and m.exam_board = d.exam_board
           and m.kind = 'point' and m.new_ref is not null
           and m.old_ref = regexp_replace(e, '^(AQA|OCR|Edexcel|WJEC)[- ]+((9PH0|7408|H556)[- ]+)?', '', 'i'))
    ), logged as (
      insert into public.spec_ref_migration_log (batch, tbl, row_id, profile_id, col, old_value, new_value)
      select '026_alevel_spec_refs', 'diagrams', id::text, profile_id, 'spec_points', to_jsonb(old_value), to_jsonb(new_value) from changes
    )
    update public.diagrams d set spec_points = c.new_value from changes c where d.id = c.id;
  end if;
