// Generates the A Level spec-ref remap migration and its rollback from
// scripts/spec-ref-map-alevel.json. Run: node scripts/gen-spec-ref-migration.mjs
// Validate the mapping first: npx tsx scripts/validate-spec-ref-map.mts
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const map = JSON.parse(readFileSync(join(root, 'scripts/spec-ref-map-alevel.json'), 'utf8'))

const BATCH = '026_alevel_spec_refs'
const QUAL = 'alevel-physics'
const BOARDS = ['AQA', 'Edexcel', 'OCR', 'WJEC']
const q = s => (s === null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)

const rows = []
for (const board of BOARDS) {
  for (const [o, n] of Object.entries(map.points[board] ?? {})) rows.push([board, 'point', o, n])
  for (const [o, n] of Object.entries(map.topics[board] ?? {})) rows.push([board, 'topic', o, n])
}
const values = rows.map(([b, k, o, n]) => `  ('${QUAL}', ${q(b)}, ${q(k)}, ${q(o)}, ${q(n)})`).join(',\n')

const up = `-- Remap saved A Level spec references to the rebuilt specification data.
--
-- The AQA, Edexcel, OCR and WJEC A Level Physics specs were rebuilt from the official
-- documents with new reference numbers (e.g. Edexcel "7.11" is now "128"; AQA "1.2" is
-- now "3.1.2"). This moves already-tagged data across so it still groups under the
-- right spec point.
--
-- What it changes (A Level Physics only, matched on qualification_id + exam_board):
--   worksheets.spec_point                  old point ref -> new point ref
--   worksheets.blocks (header specPoint)   same, inside the JSON header block
--   scheme_topics.topic_ref                old topic ref -> new topic ref, or NULL when the old
--                                          topic is now several topics (topic_label is kept)
--   diagrams.spec_points                   old refs inside the array (if the table exists)
-- Old points with no equivalent in the new spec (map.new_ref IS NULL) are left untouched.
--
-- Reversible: every change is logged in spec_ref_migration_log (old and new value per row).
-- To undo run supabase/rollbacks/${BATCH}_down.sql. Rows edited since this ran are NOT
-- overwritten by the rollback.
--
-- Generated by scripts/gen-spec-ref-migration.mjs from scripts/spec-ref-map-alevel.json.
-- Safe to run more than once: no old ref equals a new ref, so a second run changes nothing.
--
-- Dry run: replace the final \"commit;\" with \"rollback;\" and add selects of your own.
--
-- After running, worksheets still on an old ref that has no equivalent in the new spec:
--   select w.exam_board, w.spec_point, count(*) from public.worksheets w
--     join public.spec_ref_map m on m.qualification_id = w.qualification_id and m.exam_board = w.exam_board
--      and m.kind = 'point' and m.old_ref = w.spec_point and m.new_ref is null
--    group by 1, 2 order by 1, 2;

begin;

create table if not exists public.spec_ref_map (
  qualification_id text not null,
  exam_board       text not null,
  kind             text not null check (kind in ('point', 'topic')),
  old_ref          text not null,
  new_ref          text,                       -- null = no single equivalent
  primary key (qualification_id, exam_board, kind, old_ref)
);

create table if not exists public.spec_ref_migration_log (
  id          bigserial primary key,
  batch       text        not null,
  tbl         text        not null,
  row_id      text        not null,
  col         text        not null,
  old_value   jsonb,
  new_value   jsonb,
  migrated_at timestamptz not null default now()
);
create index if not exists spec_ref_migration_log_batch on public.spec_ref_migration_log (batch, tbl, col);

-- Internal bookkeeping: no policies, so only the database owner / service role can read them.
alter table public.spec_ref_map enable row level security;
alter table public.spec_ref_migration_log enable row level security;

insert into public.spec_ref_map (qualification_id, exam_board, kind, old_ref, new_ref) values
${values}
on conflict (qualification_id, exam_board, kind, old_ref) do update set new_ref = excluded.new_ref;

-- worksheets has an updated_at trigger; without this every remapped worksheet would jump to
-- "just edited" and reorder everyone's gallery.
alter table public.worksheets disable trigger worksheets_updated_at;

-- 1. worksheets.spec_point
with changes as (
  select w.id, w.spec_point as old_value, m.new_ref
  from public.worksheets w
  join public.spec_ref_map m
    on m.qualification_id = w.qualification_id and m.exam_board = w.exam_board
   and m.kind = 'point' and m.old_ref = w.spec_point
  where m.new_ref is not null
), logged as (
  insert into public.spec_ref_migration_log (batch, tbl, row_id, col, old_value, new_value)
  select '${BATCH}', 'worksheets', id::text, 'spec_point', to_jsonb(old_value), to_jsonb(new_ref) from changes
)
update public.worksheets w set spec_point = c.new_ref from changes c where w.id = c.id;

-- 2. the specPoint stored on the header block inside worksheets.blocks
with changes as (
  select w.id, h.sp as old_value, m.new_ref
  from public.worksheets w
  cross join lateral (
    select b ->> 'specPoint' as sp
    from jsonb_array_elements(w.blocks) b
    where b ->> 'type' = 'header' and b ->> 'specPoint' is not null
    limit 1
  ) h
  join public.spec_ref_map m
    on m.qualification_id = w.qualification_id and m.exam_board = w.exam_board
   and m.kind = 'point' and m.old_ref = h.sp
  where m.new_ref is not null and jsonb_typeof(w.blocks) = 'array'
), logged as (
  insert into public.spec_ref_migration_log (batch, tbl, row_id, col, old_value, new_value)
  select '${BATCH}', 'worksheets', id::text, 'blocks.header.specPoint', to_jsonb(old_value), to_jsonb(new_ref) from changes
)
update public.worksheets w
set blocks = (
  select jsonb_agg(
           case when b ->> 'type' = 'header' and b ->> 'specPoint' = c.old_value
                then jsonb_set(b, '{specPoint}', to_jsonb(c.new_ref))
                else b end
           order by ord)
  from jsonb_array_elements(w.blocks) with ordinality as t(b, ord)
)
from changes c where w.id = c.id;

alter table public.worksheets enable trigger worksheets_updated_at;

-- 3. scheme topics (only for schemes whose primary qualification is A Level Physics)
with changes as (
  select st.id, st.topic_ref as old_value, m.new_ref
  from public.scheme_topics st
  join public.schemes s on s.id = st.scheme_id
  join public.spec_ref_map m
    on m.qualification_id = s.qualification_id and m.exam_board = s.exam_board
   and m.kind = 'topic' and m.old_ref = st.topic_ref
), logged as (
  insert into public.spec_ref_migration_log (batch, tbl, row_id, col, old_value, new_value)
  select '${BATCH}', 'scheme_topics', id::text, 'topic_ref', to_jsonb(old_value), to_jsonb(new_ref) from changes
)
update public.scheme_topics st set topic_ref = c.new_ref from changes c where st.id = c.id;

-- 4. diagram library tags (the table only exists if 025_diagrams.sql has been applied)
do $$
begin
  if to_regclass('public.diagrams') is not null then
    with changes as (
      select d.id, d.spec_points as old_value,
             (select array_agg(e order by first_ord)
              from (
                select coalesce(m.new_ref, x.e) as e, min(x.ord) as first_ord
                from unnest(d.spec_points) with ordinality as x(e, ord)
                left join public.spec_ref_map m
                  on m.qualification_id = d.qualification and m.exam_board = d.exam_board
                 and m.kind = 'point' and m.old_ref = x.e and m.new_ref is not null
                group by 1
              ) z) as new_value
      from public.diagrams d
      where d.qualification = '${QUAL}'
        and exists (
          select 1 from unnest(d.spec_points) e
          join public.spec_ref_map m
            on m.qualification_id = d.qualification and m.exam_board = d.exam_board
           and m.kind = 'point' and m.old_ref = e and m.new_ref is not null)
    ), logged as (
      insert into public.spec_ref_migration_log (batch, tbl, row_id, col, old_value, new_value)
      select '${BATCH}', 'diagrams', id::text, 'spec_points', to_jsonb(old_value), to_jsonb(new_value) from changes
    )
    update public.diagrams d set spec_points = c.new_value from changes c where d.id = c.id;
  end if;
end $$;

commit;
`

const down = `-- Rollback for ${BATCH}: restores the spec references that the migration changed.
--
-- Only restores a value if it still holds what the migration wrote, so anything edited
-- since is left alone (and its log row is kept). When every logged row has been restored
-- the bookkeeping tables are dropped.
--
-- Generated by scripts/gen-spec-ref-migration.mjs.

begin;

alter table public.worksheets disable trigger worksheets_updated_at;

-- 1. worksheets.spec_point
with restore as (
  select id as log_id, row_id::uuid as wid, old_value #>> '{}' as old_v, new_value #>> '{}' as new_v
  from public.spec_ref_migration_log
  where batch = '${BATCH}' and tbl = 'worksheets' and col = 'spec_point'
), done as (
  update public.worksheets w set spec_point = r.old_v
  from restore r
  where w.id = r.wid and w.spec_point is not distinct from r.new_v
  returning r.log_id
)
delete from public.spec_ref_migration_log where id in (select log_id from done);

-- 2. header specPoint inside worksheets.blocks
with restore as (
  select id as log_id, row_id::uuid as wid, old_value #>> '{}' as old_v, new_value #>> '{}' as new_v
  from public.spec_ref_migration_log
  where batch = '${BATCH}' and tbl = 'worksheets' and col = 'blocks.header.specPoint'
), done as (
  update public.worksheets w
  set blocks = (
    select jsonb_agg(
             case when b ->> 'type' = 'header' and b ->> 'specPoint' = r.new_v
                  then jsonb_set(b, '{specPoint}', to_jsonb(r.old_v))
                  else b end
             order by ord)
    from jsonb_array_elements(w.blocks) with ordinality as t(b, ord)
  )
  from restore r
  where w.id = r.wid and jsonb_typeof(w.blocks) = 'array'
    and exists (select 1 from jsonb_array_elements(w.blocks) b
                where b ->> 'type' = 'header' and b ->> 'specPoint' = r.new_v)
  returning r.log_id
)
delete from public.spec_ref_migration_log where id in (select log_id from done);

alter table public.worksheets enable trigger worksheets_updated_at;

-- 3. scheme_topics.topic_ref
with restore as (
  select id as log_id, row_id::uuid as tid, old_value #>> '{}' as old_v, new_value #>> '{}' as new_v
  from public.spec_ref_migration_log
  where batch = '${BATCH}' and tbl = 'scheme_topics' and col = 'topic_ref'
), done as (
  update public.scheme_topics st set topic_ref = r.old_v
  from restore r
  where st.id = r.tid and st.topic_ref is not distinct from r.new_v
  returning r.log_id
)
delete from public.spec_ref_migration_log where id in (select log_id from done);

-- 4. diagrams.spec_points
do $$
begin
  if to_regclass('public.diagrams') is not null then
    with restore as (
      select id as log_id, row_id::uuid as did, old_value as old_v, new_value as new_v
      from public.spec_ref_migration_log
      where batch = '${BATCH}' and tbl = 'diagrams' and col = 'spec_points'
    ), done as (
      update public.diagrams d
      set spec_points = array(select jsonb_array_elements_text(r.old_v))
      from restore r
      where d.id = r.did and to_jsonb(d.spec_points) = r.new_v
      returning r.log_id
    )
    delete from public.spec_ref_migration_log where id in (select log_id from done);
  end if;
end $$;

-- Drop the bookkeeping tables once nothing is left to restore.
do $$
begin
  if exists (select 1 from public.spec_ref_migration_log where batch = '${BATCH}') then
    raise notice 'Some rows were edited after the migration and were not restored; spec_ref_map and spec_ref_migration_log have been kept.';
  else
    drop table if exists public.spec_ref_migration_log;
    drop table if exists public.spec_ref_map;
  end if;
end $$;

commit;
`

writeFileSync(join(root, `supabase/migrations/${BATCH.replace('_alevel_spec_refs', '')}_remap_alevel_spec_refs.sql`), up)
writeFileSync(join(root, `supabase/rollbacks/${BATCH}_down.sql`), down)
console.log(`wrote migration (${rows.length} map rows) and rollback`)
